package coverage

import (
	"os"
	"strings"
	"testing"
)

func TestHTMLReportOmitsUpstreamRepositoryLinks(t *testing.T) {
	sourceAnalysis := &SourceAnalysis{
		Files: map[string]*SourceFileAnalysis{},
	}

	reportPath, err := WriteHTMLReport(sourceAnalysis, t.TempDir())
	if err != nil {
		t.Fatalf("could not generate HTML coverage report: %v", err)
	}

	report, err := os.ReadFile(reportPath)
	if err != nil {
		t.Fatalf("could not read HTML coverage report: %v", err)
	}

	reportHTML := string(report)
	for _, unwanted := range []string{
		"https://github.com/crytic/medusa",
		"github.com/crytic/medusa",
		">GitHub</a>",
	} {
		if strings.Contains(reportHTML, unwanted) {
			t.Fatalf("HTML coverage report unexpectedly contains %q", unwanted)
		}
	}

	if !strings.Contains(reportHTML, "Report generated by Medusa on") {
		t.Fatal("HTML coverage report does not contain its generation timestamp")
	}
}
